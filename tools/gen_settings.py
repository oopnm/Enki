#!/usr/bin/env python3
"""Generates android/protocol/.../SettingsSchema.kt from protocol/settings.json.

    tools/gen_settings.py           write the file
    tools/gen_settings.py --check   fail (exit 1) if the committed file is not what the schema produces

The desktop reads protocol/settings.json directly at build time; Android gets plain Kotlin so the pure-JVM
protocol module needs no JSON library. CI runs --check, so the two apps cannot drift apart.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "protocol" / "settings.json"
OUT = ROOT / "android/protocol/src/main/kotlin/io/github/oopnm/enki/link/SettingsSchema.kt"


def q(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


def literal(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return f"{v}L"
    if isinstance(v, float):
        return repr(v)
    return q(v)


def render(schema):
    out = [
        "// GENERATED by tools/gen_settings.py from protocol/settings.json. Do not edit by hand.",
        "package io.github.oopnm.enki.link",
        "",
        "/** The settings both apps share (mirrors desktop/crates/enki-settings). */",
        "object SettingsSchema {",
        f"    const val VERSION = {schema['schema_version']}",
        "",
        "    val defs: List<SettingDef> = listOf(",
    ]
    for d in schema["settings"]:
        t = d["type"]
        if t == "bool":
            kind = "SettingKind.Bool"
        elif t == "enum":
            kind = "SettingKind.Choice(listOf(" + ", ".join(q(v) for v in d["values"]) + "))"
        elif t == "int":
            kind = f"SettingKind.Whole({int(d['min'])}L, {int(d['max'])}L, {int(d.get('step', 1))}L)"
        elif t == "float":
            kind = f"SettingKind.Decimal({float(d['min'])!r}, {float(d['max'])!r})"
        elif t == "string":
            kind = f"SettingKind.Text({int(d['max_len'])})"
        else:
            raise SystemExit(f"unknown type {t}")
        scope = "Scope.SYNCED" if d["scope"] == "synced" else "Scope.LOCAL"
        apply_ = {"live": "Apply.LIVE", "restart": "Apply.RESTART", "passive": "Apply.PASSIVE"}[d["apply"]]
        apps = d.get("apps", ["desktop", "phone"])
        on_phone = "true" if "phone" in apps else "false"
        out.append(
            f"        SettingDef({q(d['key'])}, {q(d['group'])}, {kind}, {literal(d['default'])}, {scope}, {apply_}, {on_phone}),"
        )
    out += ["    )", "", "    fun get(key: String): SettingDef? = defs.firstOrNull { it.key == key }", "}", ""]
    return "\n".join(out)


def main():
    text = render(json.loads(SCHEMA.read_text()))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run tools/gen_settings.py", file=sys.stderr)
            return 1
        print("SettingsSchema.kt is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
