#!/usr/bin/env python3
"""Generates the design tokens of both apps from protocol/tokens.json.

    tools/gen_tokens.py           write the files
    tools/gen_tokens.py --check   fail (exit 1) if a committed file is not what the tokens produce

Android gets res/values/tokens.xml (colors and dimens); the desktop gets a GTK CSS file with named colors
(@define-color). One source, so the two apps cannot drift apart. Phase 6 builds the Abzu theme on these names.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT / "protocol" / "tokens.json"
ANDROID = ROOT / "android/app/src/main/res/values/tokens.xml"
DESKTOP = ROOT / "desktop/crates/enki-gui/src/tokens.css"


def android(t):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- GENERATED by tools/gen_tokens.py from protocol/tokens.json. Do not edit. -->", "<resources>"]
    for name, value in t["colors"].items():
        lines.append(f'    <color name="enki_{name}">{value}</color>')
    for name, value in t["radius"].items():
        lines.append(f'    <dimen name="enki_radius_{name}">{value}dp</dimen>')
    for name, value in t["spacing"].items():
        lines.append(f'    <dimen name="enki_space_{name}">{value}dp</dimen>')
    lines += ["</resources>", ""]
    return "\n".join(lines)


def desktop(t):
    lines = ["/* GENERATED by tools/gen_tokens.py from protocol/tokens.json. Do not edit. */"]
    for name, value in t["colors"].items():
        lines.append(f"@define-color enki_{name} {value};")
    lines.append("")
    return "\n".join(lines)


def main():
    t = json.loads(TOKENS.read_text())
    outputs = {ANDROID: android(t), DESKTOP: desktop(t)}
    if "--check" in sys.argv:
        bad = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for p in bad:
            print(f"{p.relative_to(ROOT)} is out of date: run tools/gen_tokens.py", file=sys.stderr)
        if not bad:
            print("design tokens are up to date")
        return 1 if bad else 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
