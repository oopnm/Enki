#!/usr/bin/env python3
"""Generates the Fluent file (desktop) and the strings.xml (Android) of the added languages from one source file each.

    tools/gen_translations.py           write the files
    tools/gen_translations.py --check   fail (exit 1) if a committed file is not what the sources produce

Source: tools/translations/<lang>.ftl, one `message-id = text` per line, the same ids as desktop/i18n/en/enki.ftl plus
four Android-only ones (start, stop, camera-permission-needed, hint-connect). Both apps get the same words for the
same setting, so "both apps read the same". English, Arabic and Chinese are written by hand in both apps and are not
produced here. The first translations are machine-assisted and carry a "needs review" note until a native speaker
has read them (see docs/LANGUAGES.md).

Texts that read the same in every language (numbers, units, the name) are not repeated in the sources; the English
text is used. The names of the languages (shown in the language list) are written in their own language and are
added here too.
"""
import pathlib
import re
import sys
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "tools" / "translations"
EN_FTL = ROOT / "desktop/i18n/en/enki.ftl"
EN_XML = ROOT / "android/app/src/main/res/values/strings.xml"

NEW_LANGS = ["tr", "fa", "ckb", "es", "fr", "ru", "de", "pt", "ja", "hi"]

NATIVE = {
    "en": "English", "ar": "العربية", "zh": "中文", "tr": "Türkçe", "fa": "فارسی", "ckb": "کوردیی ناوەندی",
    "es": "Español", "fr": "Français", "ru": "Русский", "de": "Deutsch", "pt": "Português", "ja": "日本語",
    "hi": "हिन्दी",
}

# Read the same in every language: taken from English.
SAME = {
    "app-title", "status-rtt", "setting-camera-iso",
    *(f"setting-video-rotate--{d}" for d in (0, 90, 180, 270)),
    *(f"setting-camera-iso--{v}" for v in (100, 200, 400, 800, 1600, 3200)),
    *(f"setting-camera-shutter--{v}" for v in (30, 60, 120, 250, 500)),
    *(f"setting-camera-antiflicker--{v}" for v in (50, 60)),
    "setting-video-resolution--480p", "setting-video-resolution--720p", "setting-video-resolution--1080p",
    *(f"setting-video-fps--{v}" for v in (15, 24, 30, 60)),
}
ANDROID_ONLY = ["start", "stop", "camera-permission-needed", "hint-connect"]
CODE = "{ $port }"


def read_ftl(path):
    messages = {}
    for line in path.read_text().splitlines():
        m = re.match(r"^([a-zA-Z][a-zA-Z0-9_-]*)\s*=\s*(.*)$", line)
        if m and not line.startswith("#"):
            messages[m.group(1)] = m.group(2).strip()
    return messages


def en_android_names():
    return re.findall(r'<string name="([a-z0-9_]+)"', EN_XML.read_text())


def android_id(name):
    return name.replace("__", "--").replace("_", "-")


def text_for(lang, mid, source, english, errors):
    if mid.startswith("setting-ui-language--") and mid.rsplit("--", 1)[1] in NATIVE:
        return NATIVE[mid.rsplit("--", 1)[1]]
    if mid in SAME:
        return english[mid]
    if mid in source:
        return source[mid]
    errors.append(f"{lang}: no translation for {mid}")
    return english.get(mid, mid)


def header(lang, comment):
    return (
        f"{comment} GENERATED by tools/gen_translations.py from tools/translations/{lang}.ftl. Do not edit here.\n"
        f"{comment} Machine-assisted translation: needs review by a native speaker.\n"
    )


def desktop_file(lang, source, english, errors):
    out = [header(lang, "#")]
    for mid in english_order():
        out.append(f"{mid} = {text_for(lang, mid, source, english, errors)}")
    return "\n".join(out) + "\n"


def english_order():
    return [m.group(1) for m in re.finditer(r"^([a-zA-Z][a-zA-Z0-9_-]*)\s*=", EN_FTL.read_text(), re.M)]


def android_value(text):
    text = text.replace(CODE, "%1$d")
    text = escape(text).replace("'", "\\'").replace('"', '\\"')
    return text


def android_file(lang, source, english, errors):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- " + header(lang, "").strip().replace("\n", " ") + " -->", "<resources>"]
    for name in en_android_names():
        if name == "app_name":
            value = "Enki"
        else:
            mid = android_id(name)
            if mid not in english and mid not in ANDROID_ONLY:
                errors.append(f"{lang}: Android string {name} has no matching message id")
                continue
            value = text_for(lang, mid, source, english, errors) if mid in english or mid in source else None
            if value is None:
                errors.append(f"{lang}: no translation for {mid}")
                value = mid
        out.append(f'    <string name="{name}">{android_value(value)}</string>')
    out += ["</resources>", ""]
    return "\n".join(out)


def outputs():
    english = read_ftl(EN_FTL)
    errors, files = [], {}
    for lang in NEW_LANGS:
        path = SOURCES / f"{lang}.ftl"
        if not path.exists():
            errors.append(f"{path.relative_to(ROOT)} is missing")
            continue
        source = read_ftl(path)
        known = set(english) | set(ANDROID_ONLY)
        for extra in sorted(set(source) - known):
            errors.append(f"{lang}: {extra} is not an English message id")
        files[ROOT / f"desktop/i18n/{lang}/enki.ftl"] = desktop_file(lang, source, english, errors)
        files[ROOT / f"android/app/src/main/res/values-{lang}/strings.xml"] = android_file(lang, source, english, errors)
    return files, errors


def main():
    files, errors = outputs()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if "--check" in sys.argv:
        bad = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        for p in bad:
            print(f"{p.relative_to(ROOT)} is out of date: run tools/gen_translations.py", file=sys.stderr)
        if not bad:
            print("generated translations are up to date")
        return 1 if bad else 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
